import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { SessionManager } from '@earendil-works/pi-coding-agent';
import { startServer } from '../server.mjs';
import { Organization } from '../organization.mjs';
import { documentPrivacy, documentScopePrivacy } from '../rag-tools.mjs';

test('chats and projects isolate artefacts, share project conversations, preserve Git history and restore selection', async t => {
  const root = await mkdtemp(path.join(tmpdir(), 'haas-organization-'));
  const options = { port: 0, dataDir: path.join(root, 'data'), workspace: path.join(root, 'legacy'), chatOptions: { extensions: [] } };
  let app;
  t.after(async () => { await app?.close(); await rm(root, { recursive: true, force: true }); });
  app = await startServer(options);
  const request = (url, input) => fetch(`${app.url}${url}`, { method: 'POST', headers: { 'X-Haas-Request': '1', 'Content-Type': 'application/json' }, body: JSON.stringify(input || {}) });
  const post = async (url, input) => { const response = await request(url, input); assert.equal(response.status, 200, await response.text()); };
  const state = async () => (await fetch(`${app.url}/api/state`)).json();
  const upload = async name => {
    const response = await fetch(`${app.url}/api/upload?name=${name}`, { method: 'POST', headers: { 'X-Haas-Request': '1' }, body: 'Original design bytes' });
    assert.equal(response.status, 200); return (await response.json()).path;
  };
  const organization = new Organization(options.dataDir);
  let current = await state();
  assert.equal(current.scope.kind, 'chat');
  assert.equal(current.scope.gitTracked, false);
  const firstChat = current.conversations.find(item => item.active).id;
  const firstChatScope = current.scope.id;
  const chatFile = await upload('idea.txt');
  await post('/api/git', { enabled: true });
  assert.equal((await state()).scope.gitTracked, true);
  const standalone = await organization.get('chat', firstChatScope);
  assert.match(await organization.git(standalone, ['ls-files']), /idea.txt/);

  assert.equal((await request('/api/projects', { name: ' ' })).status, 400);
  await post('/api/projects', { name: 'Railway', description: 'Build a long-term layout' });
  current = await state();
  const projectId = current.scope.id;
  assert.equal(current.scope.kind, 'project');
  assert.equal(current.scope.gitTracked, false);
  assert.equal(current.files.length, 0);
  assert.equal((await fetch(`${app.url}/files/${chatFile}`)).status, 404);
  const project = await organization.get('project', projectId);
  const projectFile = await upload('layout.xtc');
  const saved = SessionManager.open(path.join(project.sessionDir, project.currentSession), project.sessionDir, project.workspace);
  saved.appendMessage({ role: 'user', content: 'Plan a railway', timestamp: Date.now() });
  saved.appendMessage({ role: 'assistant', content: [{ type: 'text', text: 'Layout discussion.' }], api: 'openai-completions', provider: 'ollama', model: 'test', stopReason: 'stop', timestamp: Date.now() });
  const firstConversation = saved.getSessionId();
  await post('/api/projects/conversations/new');
  current = await state();
  assert.equal(current.scope.id, projectId);
  assert.deepEqual(current.files.map(file => file.path), [projectFile]);
  assert.equal(current.messages.length, 0);
  assert.equal(current.conversations.filter(item => item.scopeId === projectId).length, 2);
  await post('/api/conversations/open', { id: firstConversation });
  assert.ok((await state()).messages.some(message => message.text === 'Layout discussion.'));
  await post('/api/git', { enabled: true });
  const initial = (await organization.git(project, ['rev-parse', 'HEAD'])).trim();
  assert.match(await organization.git(project, ['ls-files']), /sessions\/.+\.jsonl/);
  assert.match(await organization.git(project, ['ls-files']), /layout.xtc/);
  assert.doesNotMatch(await organization.git(project, ['ls-files']), /auth.json|mcp.log|originals\//);
  await post('/api/git', { enabled: false });
  assert.equal((await state()).scope.gitTracked, false);
  await writeFile(path.join(current.workspace, 'notes.md'), 'Progress while tracking is off');
  await post('/api/git', { enabled: true });
  assert.match(await organization.git(project, ['log', '--format=%H']), new RegExp(initial));
  assert.match(await organization.git(project, ['ls-files']), /notes.md/);
  const beforeUpload = (await organization.git(project, ['rev-parse', 'HEAD'])).trim();
  await upload('new-design.txt');
  assert.notEqual((await organization.git(project, ['rev-parse', 'HEAD'])).trim(), beforeUpload);
  await post('/api/new');
  assert.equal((await state()).files.length, 0);
  await post('/api/conversations/open', { id: firstChat });
  assert.equal((await state()).scope.id, firstChatScope);
  assert.equal((await state()).scope.gitTracked, true);
  await post('/api/projects/open', { id: projectId });
  assert.equal((await state()).conversations.find(item => item.active).id, firstConversation);
  assert.equal((await request('/api/projects/open', { id: '../../outside' })).status, 404);
  await app.close(); app = await startServer(options);
  current = await state();
  assert.equal(current.scope.id, projectId);
  assert.equal(current.scope.gitTracked, true);
  assert.ok(current.files.some(file => file.path === 'notes.md'));
});

test('migration retains legacy bytes and IDs, runs once and carries document privacy across the project', async t => {
  const root = await mkdtemp(path.join(tmpdir(), 'haas-migrate-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const data = path.join(root, 'data');
  const workspace = path.join(root, 'workspace');
  await mkdir(workspace); await writeFile(path.join(workspace, 'board.bin'), Buffer.from([0, 255, 19]));
  const session = SessionManager.create(workspace, path.join(data, 'sessions'));
  session.appendMessage({ role: 'user', content: 'Private work', timestamp: Date.now() });
  session.appendCustomEntry('rag-local-only', { accessedAt: 'test' });
  session.appendMessage({ role: 'assistant', content: [{ type: 'text', text: 'Done.' }], api: 'openai-completions', provider: 'ollama', model: 'test', stopReason: 'stop', timestamp: Date.now() });
  const organization = new Organization(data);
  await organization.migrate(workspace);
  const project = await organization.get('project', 'imported-workspace');
  assert.equal((await organization.sessions(project))[0].id, session.getSessionId());
  assert.deepEqual(await readFile(path.join(project.workspace, 'board.bin')), Buffer.from([0, 255, 19]));
  assert.deepEqual(await readFile(path.join(workspace, 'board.bin')), Buffer.from([0, 255, 19]));
  await writeFile(path.join(project.workspace, 'board.bin'), 'Updated');
  await organization.migrate(workspace);
  assert.equal(await readFile(path.join(project.workspace, 'board.bin'), 'utf8'), 'Updated');
  const manager = { getEntries: () => [] };
  assert.equal(await documentScopePrivacy(manager, path.join(project.root, 'local-only.json')), true);
  const handlers = {};
  documentPrivacy({}, { privacyFile: path.join(project.root, 'local-only.json') })({ on: (name, handler) => { handlers[name] = handler; } });
  assert.equal((await handlers.tool_call({ toolName: 'web_search' }, { sessionManager: manager })).block, true);
  assert.equal(await organization.tracking(project), false);
});
